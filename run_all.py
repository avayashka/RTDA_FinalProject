import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from sources.config import RESULTS_DIR

STEPS = ["tests", "timeseries", "train", "stream", "broker", "benchmark", "distributed", "spark", "summary"]


def banner(name):
    print("\n" + "=" * 78 + f"\n  STEP: {name}\n" + "=" * 78, flush=True)


def step_tests(_):
    return subprocess.call([sys.executable, "-m", "pytest", "-q", str(ROOT / "tests")], cwd=ROOT) == 0


def step_timeseries(_):
    from sources.time_series_analysis import run_analysis
    s = run_analysis()
    print(f"orbital period: {s['orbital_period_latitude_phase']['median_min']} min (latitude phase), "
          f"{s['orbital_period_vis_viva']['period_min']} min (vis-viva); segments: {s['segments']['count']}")
    return True


def step_train(_):
    from sources.train_models import run_anomaly_experiment, run_forecast_experiment, run_noise_sensitivity
    run_anomaly_experiment()
    run_noise_sensitivity()
    run_forecast_experiment()
    return True


def step_stream(_):
    from sources.stream_processor import run_pipeline
    run_pipeline(source="csv", batch_size=50, reset_db=True)
    return True


def step_broker(_):
    from sources.config import DATA_DIR
    from sources.stream_processor import run_pipeline
    s = run_pipeline(source="broker", backend="auto", batch_size=100, db_path=DATA_DIR / "iss_broker_run.db",
                     verbose=False)
    print(f"broker backend={s['config']['backend']}  events={s['events_out']}  "
          f"throughput={s['throughput_eps']} ev/s  partitions={s['config'].get('partition_sizes')}")
    with open(RESULTS_DIR / "broker_run_summary.json", "w") as fh:
        json.dump(s, fh, indent=2, default=str)
    return True


def step_benchmark(a):
    from sources.benchmark_test import run_all as bench
    bench(1500 if a.quick else 3000)
    return True


def step_distributed(a):
    from sources.distributed_pipeline import scaling_experiment
    scaling_experiment(4, (1, 2, 4), 2000 if a.quick else 8640)
    return True


def step_spark(_):
    try:
        import pyspark
    except ImportError:
        print("PySpark not installed -> skipped (pip install pyspark; needs Java 11/17).")
        return None
    return subprocess.call([sys.executable, "-m", "sources.partD", "--mode", "batch"], cwd=ROOT) == 0


def step_summary(_):
    def load(name):
        p = RESULTS_DIR / name
        return json.loads(p.read_text()) if p.exists() else {}
    ts, an, fc = load("time_series_summary.json"), load("anomaly_evaluation.json"), load("forecast_evaluation.json")
    st, bm, ds = load("stream_run_summary.json"), load("benchmark_summary.json"), load("distributed_scaling.json")
    lines = ["# Key results (auto-generated by run_all.py)", ""]
    if ts:
        lines += ["## Data & time series",
                  f"- {ts['n_events']} events, 10-s cadence, {ts['natural_discontinuities']} natural trajectory "
                  f"discontinuities -> {ts['segments']['count']} continuous segments (median {ts['segments']['median_len']} samples)",
                  f"- Orbital period: {ts['orbital_period_latitude_phase']['median_min']} min (latitude phase), "
                  f"{ts['orbital_period_vis_viva']['period_min']} min (vis-viva); naive FFT gives "
                  f"{ts['naive_fft_dominant_period_min']} min (wrong, segments mixed)",
                  f"- corr(altitude, speed) = {ts['corr_altitude_speed']}", ""]
    if an:
        lines += ["## Anomaly detection (test split)", "", "| method | precision | recall | F1 | PR-AUC | false alarms/h |",
                  "|---|---|---|---|---|---|"]
        for m, r in an["test_metrics"].items():
            lines.append(f"| {m} | {r['precision']} | {r['recall']} | {r['f1']} | {r.get('pr_auc')} | {r.get('false_alarms_per_hour')} |")
        lines += ["", f"Primary method selected on validation: **{an['primary_method']}**", ""]
    if fc:
        lines += ["## Forecasting (test split, position MAE km)", "", "| horizon | persistence | constant velocity | ridge | gradient boosting |",
                  "|---|---|---|---|---|"]
        rows = {}
        for r in fc["results"]:
            rows.setdefault(r["horizon_sec"], {})[r["model"]] = r["pos_mae_km"]
        for h, r in rows.items():
            lines.append(f"| {h} s | {r['persistence']} | {r['constant_velocity']} | {r['ridge']} | {r['gradient_boosting']} |")
        lines.append("")
    if st:
        lines += ["## Streaming run", f"- {st['events_in']} events in, {st['events_out']} processed, "
                  f"{st['throughput_eps']} events/s, latency p50/p95/p99 = {st['latency_ms']['p50']}/"
                  f"{st['latency_ms']['p95']}/{st['latency_ms']['p99']} ms",
                  f"- cleaning: {st['cleaning']['rejected']}",
                  f"- online detection (test period): {st.get('online_detection_test_period')}",
                  f"- online forecast: {st.get('online_forecast')}", ""]
    if bm:
        lines += ["## Performance", "", "| batch | events/s | p95 ms | CPU % | bottleneck |", "|---|---|---|---|---|"]
        for r in bm["batch_sweep"]:
            lines.append(f"| {r['batch_size']} | {r['throughput_eps']} | {r['latency_p95_ms']} | {r['cpu_pct_of_one_core']} | {r['bottleneck_stage']} |")
        lines += ["", f"Storage pattern: {bm['storage_pattern']}", ""]
    if ds:
        lines += ["## Distributed scaling", "", "| workers | events/s | speed-up | efficiency | identical results |",
                  "|---|---|---|---|---|"]
        for r in ds["results"]:
            lines.append(f"| {r['workers']} | {r['throughput_eps']} | {r['speedup']} | {r['efficiency']} | {r['results_identical_to_1_worker']} |")
        lines.append(f"\nCPU cores on the test machine: {ds['cpu_cores']}")
    (RESULTS_DIR / "summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return True


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--skip", nargs="*", default=[], choices=STEPS)
    ap.add_argument("--only", nargs="*", default=None, choices=STEPS)
    args = ap.parse_args()
    status = {}
    t_all = time.time()
    for name in STEPS:
        if name in args.skip or (args.only and name not in args.only):
            continue
        banner(name)
        t0 = time.time()
        ok = globals()[f"step_{name}"](args)
        status[name] = ("skipped" if ok is None else "ok" if ok else "FAILED", round(time.time() - t0, 1))
    print("\n" + "=" * 78)
    for k, (s, t) in status.items():
        print(f"  {k:<12} {s:<8} {t:>6.1f}s")
    print(f"  total {time.time() - t_all:.0f}s")
    sys.exit(1 if any(s == "FAILED" for s, _ in status.values()) else 0)